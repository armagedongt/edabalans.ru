const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const {createRequire} = require('node:module');
const {chromium} = createRequire(process.env.NODE_PATH+'/package.json')('./');
(async () => {
  const out = process.argv[2]; fs.mkdirSync(out,{recursive:false});
  const sourceRoot = 'D:/Codex/work/article-family-integration-20260925/work/blog-reader-preview-20261001';
  const source = fs.readFileSync(path.join(sourceRoot,'serve.py'),'utf8').match(/channel = '''([\s\S]*?)''' \+ telegram_icon \+ '''([\s\S]*?)'''/);
  const telegram = fs.readFileSync('backend/app/static/intensive/index.html','utf8').match(/channel-button--telegram[^>]*>(<svg.*?<\/svg>)/)[1];
  const sourceChannel = (source[1]+telegram+source[2]).replace('/preview/avatar.webp','/blog/assets/sergey-author-channel.webp').replace('/preview/max-logo.png','/blog/assets/reader-max-logo.png');
  const browser = await chromium.launch({headless:true,channel:'msedge'});
  const rows=[];
  try {
    for (const width of (process.argv[3] ? [Number(process.argv[3])] : [360,430,768,899,900,901,1440])) for (const theme of ['light','dark']) {
      const page = await browser.newPage({viewport:{width,height:900},reducedMotion:'reduce'});
      const errors=[]; page.on('pageerror',e=>errors.push(e.message));
      let state={recognized:false,show_subscription:true,telegram:{url:'https://t.me/Fitness_Talks_bot'}};
      await page.route('**/blog/reader/context',route=>state ? route.fulfill({json:state}) : route.fulfill({status:503,body:'unavailable'}));
      await page.route('https://**/*',route=>route.fulfill({body:'',contentType:'text/javascript'}));
      const url='http://127.0.0.1:8788/blog/articles/pochemu-yapontsy-hudye-a-ty-net';
      await page.goto(url);
      await page.evaluate(t=>document.documentElement.dataset.theme=t,theme);
      await page.locator('#reader-channel-inline').waitFor();
      const inline=page.locator('#reader-channel-inline');
      const popup=page.locator('#reader-popup');
      assert.equal(await popup.evaluate(node=>node.open),false, 'No popup before half the author material');
      assert.equal(await inline.locator('.reader-bot-telegram').getAttribute('href'),state.telegram.url);
      await page.locator('#reader-sheet').evaluate(node=>node.showModal());
      await page.evaluate(()=>{scrollTo(0,document.body.scrollHeight);window.dispatchEvent(new Event('scroll'));});
      assert.equal(await popup.evaluate(node=>node.open),false,'Contents has priority over popup');
      await page.locator('#reader-sheet').evaluate(node=>node.close());
      await inline.scrollIntoViewIfNeeded();
      await page.waitForFunction(()=>document.getElementById('reader-popup').open);
      assert.equal(await page.evaluate(()=>getComputedStyle(document.documentElement).overflow),'hidden');
      assert.ok(await page.evaluate(()=>document.getElementById('reader-popup').contains(document.activeElement)));
      await popup.screenshot({path:path.join(out,`${width}-${theme}-popup.png`)});
      await page.screenshot({path:path.join(out,`${width}-${theme}-context.png`)});
      assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
      await page.keyboard.press('Escape');
      assert.equal(await popup.evaluate(node=>node.open),false);
      assert.notEqual(await page.evaluate(()=>getComputedStyle(document.documentElement).overflow),'hidden');
      await inline.screenshot({path:path.join(out,`${width}-${theme}-inline.png`)});
      await page.reload();
      await page.evaluate(t=>document.documentElement.dataset.theme=t,theme);
      await page.locator('#reader-channel-inline').waitFor();
      await page.locator('#reader-channel-inline').scrollIntoViewIfNeeded();
      assert.equal(await popup.evaluate(node=>node.open),false);
      state={recognized:true,show_subscription:false,telegram:{url:'https://t.me/Fitness_Talks/260'}};
      await page.reload();
      await page.evaluate(t=>document.documentElement.dataset.theme=t,theme);
      await page.waitForLoadState('networkidle');
      assert.equal(await page.locator('#reader-channel-inline').count(),0);
      await page.evaluate(()=>scrollTo(0,document.body.scrollHeight));
      assert.equal(await popup.evaluate(node=>node.open),false);
      state={recognized:true,show_subscription:true,telegram:{url:'https://t.me/Fitness_Talks/260'}};
      await page.reload();
      await page.evaluate(t=>document.documentElement.dataset.theme=t,theme);
      await page.locator('#reader-channel-inline').waitFor();
      assert.equal(await page.locator('#reader-channel-inline .reader-bot-telegram').getAttribute('href'),state.telegram.url);
      await popup.locator('.reader-channel').evaluate((node,html)=>node.outerHTML=html,sourceChannel);
      await page.addStyleTag({content:fs.readFileSync(path.join(sourceRoot,'reader.css'),'utf8')});
      await popup.evaluate(node=>node.showModal());
      await popup.screenshot({path:path.join(out,`${width}-${theme}-source-popup.png`)});
      await popup.evaluate(node=>node.close());
      await page.locator('#reader-channel-inline').evaluate((node,html)=>node.outerHTML=html.replace('class="reader-channel blog-cta"','id="reader-channel-inline" class="reader-channel blog-cta"'),sourceChannel);
      await page.locator('#reader-channel-inline').evaluate(node=>{const rect=node.getBoundingClientRect();scrollBy(0,rect.top-(innerHeight-rect.height)/2);});
      await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
      await page.locator('#reader-channel-inline').screenshot({path:path.join(out,`${width}-${theme}-source-inline.png`)});
      state=null;
      await page.context().clearCookies();
      await page.reload();
      await page.evaluate(t=>document.documentElement.dataset.theme=t,theme);
      await page.locator('#reader-channel-inline').waitFor();
      assert.equal(await page.locator('#reader-channel-inline .reader-bot-telegram').getAttribute('href'),'https://t.me/Fitness_Talks_bot');
      await page.locator('#reader-channel-inline').scrollIntoViewIfNeeded();
      await page.waitForFunction(()=>document.getElementById('reader-popup').open);
      assert.deepEqual(errors,[]);
      rows.push({width,theme,guest:true,subscriberHidden:true,knownBotStartPin:true,contextErrorGuest:true,modalScrollLock:true,escape:true,interval24h:true,overflow:false,pageErrors:errors});
      await page.close();
    }
    fs.writeFileSync(path.join(out,'browser.json'),JSON.stringify(rows,null,2));
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
