def refresh_product_content(payload: dict) -> dict:
    """Apply an explicitly approved content refresh without changing access rules."""
    result = normalize_product_catalog(payload)
    for item in result.get("products", []):
        code = item.get("code")
        if code in MARKETING_CONTEXTS:
            item["marketing"] = MARKETING_CONTEXTS[code]
        if code in CONTENT_DESCRIPTOR_REFRESH:
            item["descriptor"] = CONTENT_DESCRIPTOR_REFRESH[code]
    return result

