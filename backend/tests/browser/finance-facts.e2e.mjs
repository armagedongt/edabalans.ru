import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import path from 'node:path';
const require=createRequire(import.meta.url);
const {chromium}=process.env.CODEX_NODE_MODULES?require(path.join(process.env.CODEX_NODE_MODULES,'playwright')):await import('playwright');
const base=process.env.FINANCE_QA_BASE_URL;
if(!base)throw new Error('Set FINANCE_QA_BASE_URL to the isolated demo server; never target production');
assert(['127.0.0.1','localhost','[::1]'].includes(new URL(base).hostname),'Use a loopback-only demo server');
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:430,height:900}});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
let createdPlan=null;
let originalExpenses=null;
try{
 const response=await page.goto(base+'/finance');
 assert.equal(response.headers()['x-finance-demo'],'1','Writes require an explicitly marked demo server');
 await page.waitForFunction(()=>window.financeModel&&!document.getElementById('save').disabled);
 await page.getByText('Локальный просмотр · демонстрационные данные, реальная база не подключена',{exact:true}).waitFor();
 const planIncome=await page.locator('#personal').textContent();
 const planParameters=await page.evaluate(()=>window.financeModel.values());
 assert(!('paidConversion30' in planParameters),'legacy plans must not invent early/late proportions');
 const savedResponse=page.waitForResponse(response=>response.url().endsWith('/admin/api/finance/plans')&&response.request().method()==='POST');
 await page.locator('#plan-name').fill('Проверка legacy-снимка');await page.locator('#save').click();
 createdPlan=(await(await savedResponse).json()).plan.id;
 await page.reload();await page.waitForFunction(()=>!document.getElementById('save').disabled);
 assert.equal(await page.locator('#personal').textContent(),planIncome);
 assert.deepEqual(await page.evaluate(()=>window.financeModel.values()),planParameters);
 await page.locator('[data-finance-mode="month"]').click();
 await page.waitForFunction(()=>!document.getElementById('fact-view').hasAttribute('aria-busy'));
 await page.locator('#fact-month').fill('2026-10');await page.locator('#fact-month').dispatchEvent('change');
 await page.waitForFunction(()=>!document.getElementById('fact-view').hasAttribute('aria-busy'));
 assert(await page.locator('#fact-view').isVisible());
 assert(!await page.locator('#plan-view').isVisible());
 const month=await page.locator('#fact-month').inputValue();
 const source=await page.evaluate(async m=>(await (await fetch('/admin/api/finance/facts?month='+m)).json()),month);
 originalExpenses={month,ads:source.expenses.ads,opex:source.expenses.opex};
 const renderedTurnover=await page.locator('#turnover').textContent();
 assert(renderedTurnover.replace(/[^0-9]/g,'')===String(Math.round(source.receipts.revenue)));
 const displayedMoney=async id=>(await page.locator('#'+id).textContent()).replace(/[^0-9−-]/g,'').replace('−','-');
 async function checkFacts(data,ads,opex){
   const income=ads===null||opex===null?null:data.receipts.revenue*(1-planParameters.feeRate/100)-ads-opex;
   const units=data.categories.filter(x=>['CONSULTATION','MASTERCLASS_CONSULT'].includes(x.code)).reduce((n,x)=>n+x.payments,0);
   const labor=data.support.other_payments?null:(units+data.support.monthly_payments*2)*planParameters.timeUnit;
   assert.equal(await displayedMoney('personal'),income===null?'':String(Math.round(income)));
   assert.equal(await displayedMoney('consult-income'),labor===null?'':String(Math.round(labor)));
   assert.equal(await displayedMoney('business-margin'),income===null||labor===null?'':String(Math.round(income-labor)));
   const fees=page.locator('#fact-money .row').filter({hasText:'Налоги + эквайринг'}).locator('b');
   assert.equal((await fees.textContent()).replace(/[^0-9]/g,''),String(Math.round(data.receipts.revenue*planParameters.feeRate/100)));
 }
 await checkFacts(source,source.expenses.ads,source.expenses.opex);
 const septemberUrl='**/admin/api/finance/facts?month=2026-09';
 await page.route(septemberUrl,route=>route.fulfill({status:503,body:'temporarily unavailable'}));
 await page.locator('#fact-month').fill('2026-09');await page.locator('#fact-month').dispatchEvent('change');
 await page.locator('#fact-retry').waitFor();
 assert(!await page.locator('.fact-grid').isVisible(),'old period rows must not remain visible on request failure');
 assert.equal(await page.locator('#turnover').textContent(),'—');
 await page.unroute(septemberUrl);await page.locator('#fact-retry').click();
 await page.waitForFunction(()=>!document.getElementById('fact-view').hasAttribute('aria-busy'));
 assert(await page.locator('.fact-grid').isVisible());
 const september=await page.evaluate(async ()=>(await (await fetch('/admin/api/finance/facts?month=2026-09')).json()));
 assert.equal(september.support.other_payments,0,'September exercises numeric monthly subscription labor');
 assert(september.support.monthly_payments>0);
 assert(september.expenses.ads!==null&&september.expenses.opex!==null);
 await checkFacts(september,september.expenses.ads,september.expenses.opex);
 await page.locator('#fact-month').fill(month);await page.locator('#fact-month').dispatchEvent('change');
 await page.waitForFunction(()=>!document.getElementById('fact-view').hasAttribute('aria-busy'));
 await page.locator('#expense-ads').fill('9000');
 await page.locator('#expense-opex').fill('3500');
 await page.locator('#fact-expenses button').click();
 await page.locator('#expense-status').filter({hasText:'Расходы сохранены'}).waitFor();
 await page.waitForFunction(()=>!document.getElementById('fact-view').hasAttribute('aria-busy'));
 assert.equal((await page.locator('#ads-card').textContent()).replace(/[^0-9]/g,''),'9000');
 await checkFacts(source,9000,3500);
 await page.locator('#expense-ads').fill('');await page.locator('#expense-opex').fill('0');
 await page.locator('#fact-expenses button').click();
 await page.waitForFunction(()=>document.getElementById('ads-card').textContent==='—'&&!document.getElementById('fact-view').hasAttribute('aria-busy'));
 await checkFacts(source,null,0);
 await page.locator('[data-finance-mode="all"]').click();
 await page.waitForFunction(()=>!document.getElementById('fact-view').hasAttribute('aria-busy'));
 assert.match(await page.locator('#fact-title').textContent(),/1 сентября 2026/);
 assert(!await page.locator('#fact-expenses').isVisible());
 await page.locator('[data-finance-mode="plan"]').click();
 assert.equal(await page.locator('#personal').textContent(),planIncome);
 assert.deepEqual(await page.evaluate(()=>window.financeModel.values()),planParameters);
 const parts={paidConversion30:2,paidConversionLater:planParameters.conversion-2,organicConversion30:3,organicConversionLater:2};
 for(const [id,value] of Object.entries(parts)){await page.locator('#'+id).fill(String(value));await page.locator('#'+id).dispatchEvent('change');}
 assert.equal(await page.locator('#personal').textContent(),planIncome,'split paid rate keeps the same total and money');
 const expectedOrganic=new Intl.NumberFormat('ru-RU',{maximumFractionDigits:1}).format(planParameters.organic/.05);
 assert((await page.locator('#plan-leads-extra').textContent()).includes(expectedOrganic));
 await page.locator('#paidConversionLater').fill(String(planParameters.conversion));await page.locator('#paidConversionLater').dispatchEvent('change');
 const expectedLeads=planParameters.paid/((planParameters.conversion+2)/100);
 assert.equal(await displayedMoney('ads-card'),String(Math.round(expectedLeads*planParameters.cpl)));
 const oldAds=planParameters.paid/(planParameters.conversion/100)*planParameters.cpl;
 const oldIncome=Number(planIncome.replace(/[^0-9−-]/g,'').replace('−','-'));
 assert(Math.abs(Number(await displayedMoney('personal'))-(oldIncome+oldAds-expectedLeads*planParameters.cpl))<=1);
 // An invalid rate must not be stored as a normal financial scenario.
 await page.locator('#paidConversionLater').fill('99');await page.locator('#paidConversionLater').dispatchEvent('change');
 assert.equal(await page.locator('#personal').textContent(),'—');
 await page.locator('#save').click();
 await page.locator('#saved').filter({hasText:'Сумма конверсий'}).waitFor();
 const coached=source.people.find(person=>person.support.monthly_payments>0);
 assert(coached,'The demo fixture needs a monthly subscriber');
 await page.goto(base+'/crm?user='+encodeURIComponent(coached.user_id));
 await page.locator('.crm-coaching-payments').waitFor();
 assert.match(await page.locator('.crm-coaching-payments').textContent(),/2 оплат/);
 assert.equal(errors.length,0,errors.join('; '));
 console.log('finance facts e2e: switch modes, period API, manual expenses, unchanged plan, split-rate validation OK');
}finally{
 if(originalExpenses)await page.request.post(base+'/admin/api/finance/expenses',{headers:{'X-Finance-Write':'1'},data:originalExpenses});
 if(createdPlan)await page.request.delete(base+'/admin/api/finance/plans/'+createdPlan,{headers:{'X-Finance-Write':'1'}});
 await browser.close();
}
